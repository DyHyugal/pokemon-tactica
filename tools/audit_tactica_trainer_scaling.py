#!/usr/bin/env python3
"""Inventory every HnS map/trainer pair and freeze real party-creation cases."""
from __future__ import annotations

import argparse
import csv
import json
import io
import re
from pathlib import Path

from sync_tactica_trainer_levels import map_floors, trainer_ids
from validate_tactica_boss_sets import boss_parties

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / 'test/tactica_trainer_scaling_cases.h'


def inventory():
    source = (ROOT / 'src/data/trainers_hns.party').read_text()
    protected = set(json.loads((ROOT / 'data/spec/trainer_levels.json').read_text())['protected_classes'])
    eligible = set(trainer_ids(source, protected))
    classes = set(re.findall(r'^Class: (.+)$', source, re.M)) - protected
    rosters = {trainer: mons for trainer, difficulty, mons in boss_parties(source, classes)
               if trainer in eligible and difficulty == 'Normal'}
    maps = [dict(json.loads(p.read_text()), _directory=p.parent)
            for p in sorted((ROOT / 'data/maps').glob('*_hns/map.json'))]
    tables = json.loads((ROOT / 'data/spec/encounters_standard.json').read_text())['tables']
    floors = map_floors(tables, maps)
    ceilings = map_floors([dict(t, min_level=t['max_level']) for t in tables], maps)
    pairs = set()
    for area in maps:
        scripts = area['_directory'] / 'scripts.inc'
        if scripts.exists():
            for trainer in set(re.findall(r'\bTRAINER_\w+', scripts.read_text())) & eligible:
                pairs.add((area['id'], trainer))
    # The map scripts name the first fight; later parties live in REMATCH().
    rematches = (ROOT / 'src/battle_setup.c').read_text()
    map_ids = {area['id'] for area in maps}
    for body in re.findall(r'= REMATCH\(([^)]+)\)', rematches):
        fields = [part.strip() for part in body.split(',')]
        if fields[-1] in map_ids:
            pairs.update((fields[-1], trainer) for trainer in fields[:-1] if trainer in eligible)
    missing = eligible - {trainer for _, trainer in pairs}
    return maps, sorted(pairs), floors, ceilings, rosters, sorted(missing)


def fixture_text(pairs, floors, ceilings):
    return ('// Generated by tools/audit_tactica_trainer_scaling.py --write-fixture.\n'
            '// Every ordinary trainer referenced by a map script or rematch table.\n'
            + ''.join(f'    {{{area}, {trainer}, {floors.get(area, 0)}, {ceilings.get(area, 0)}}},\n'
                      for area, trainer in pairs))


def csv_report(maps, pairs, floors, ceilings, rosters):
    """UTF-8 BOM and semicolons for direct import in French Excel."""
    output = io.StringIO(newline='')
    writer = csv.writer(output, delimiter=';', lineterminator='\n')
    writer.writerow(['Carte', 'Section', 'Dresseur', 'Niveaux ecrits', 'Plancher zone', 'Plafond zone',
                     'Avant rival', 'Apres premier rival', 'Apres Blanche', 'Apres Ligue 2'])
    by_map = {area['id']: area for area in maps}
    for area, trainer in pairs:
        levels = [int(mon['Level']) for mon in rosters[trainer]]
        bands = []
        for story in [0, 18, 29, 100]:
            floor = max(floors.get(area, 0), story)
            ceiling = max(ceilings.get(area, 0), story)
            bands.append('/'.join(str(min(100, max(level, min(max(min(levels), floor) + level - min(levels), ceiling))))
                                  for level in levels))
        writer.writerow([area, by_map[area]['region_map_section'], trainer, '/'.join(map(str, levels)),
                         floors.get(area, 0), ceilings.get(area, 0), *bands])
    for area in maps:
        if not any(key == area['id'] for key, _ in pairs):
            writer.writerow([area['id'], area['region_map_section'], '(aucun dresseur ordinaire reference)', '',
                             floors.get(area['id'], 0), ceilings.get(area['id'], 0), '', '', '', ''])
    return '\ufeff' + output.getvalue()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--write-fixture', action='store_true')
    parser.add_argument('--report-dir', type=Path)
    args = parser.parse_args()
    maps, pairs, floors, ceilings, rosters, missing = inventory()
    expected = fixture_text(pairs, floors, ceilings)
    if args.write_fixture:
        FIXTURE.write_text(expected)
    elif not FIXTURE.exists() or FIXTURE.read_text() != expected:
        raise SystemExit('Map/trainer coverage stale: run --write-fixture')
    result = dict(maps=len(maps), maps_with_ordinary_trainers=len({area for area, _ in pairs}),
                  map_trainer_pairs=len(pairs), placed_trainer_ids=len({trainer for _, trainer in pairs}),
                  unreferenced_trainer_ids=missing,
                  occupied_maps_without_zone_floor=sorted({area for area, _ in pairs} - floors.keys()))
    print(json.dumps(result, ensure_ascii=False))
    if args.report_dir:
        args.report_dir.mkdir(parents=True, exist_ok=True)
        (args.report_dir / 'tactica-trainer-scaling-inventory.json').write_text(json.dumps(result, indent=2)+'\n')
        (args.report_dir / 'tactica-trainer-scaling.csv').write_bytes(csv_report(maps, pairs, floors, ceilings, rosters).encode('utf-8'))
    else:
        report = ROOT / 'docs/assets/tactica-trainer-scaling.csv'
        if not report.exists() or report.read_text(encoding='utf-8') != csv_report(maps, pairs, floors, ceilings, rosters).replace('\r\n', '\n'):
            raise SystemExit('Scaling CSV stale: run --report-dir docs/assets')



if __name__ == '__main__':
    main()
