#!/usr/bin/env python3
"""Derive ordinary-trainer eligibility and map floors from canonical Tactica data."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/data/tactica_trainer_levels.h"


def trainer_ids(source: str, protected: set[str]) -> list[str]:
    sections = re.split(r"(?m)^=== (TRAINER_\w+) ===\s*$", source)
    eligible = set()
    for index in range(1, len(sections), 2):
        trainer, body = sections[index:index + 2]
        match = re.search(r"(?m)^Class: (.+)$", body)
        if trainer.endswith("_HNS") and match and match.group(1).strip() not in protected:
            eligible.add(trainer)
    if not eligible:
        raise ValueError("No ordinary HnS trainers found")
    return sorted(eligible)


def map_floors(tables: list[dict], maps: list[dict]) -> dict[str, int]:
    exact: dict[str, int] = {}
    for table in tables:
        exact[table["map"]] = max(exact.get(table["map"], 0), table["min_level"])
    sections: dict[str, int] = {}
    for map_data in maps:
        if map_data["id"] in exact:
            section = map_data["region_map_section"]
            sections[section] = min(sections.get(section, 100), exact[map_data["id"]])
    return {
        m["id"]: exact.get(m["id"], sections.get(m["region_map_section"], 0))
        for m in maps
        if exact.get(m["id"], sections.get(m["region_map_section"], 0))
    }


def render() -> str:
    spec = json.loads((ROOT / "data/spec/trainer_levels.json").read_text())
    ids = trainer_ids((ROOT / "src/data/trainers_hns.party").read_text(), set(spec["protected_classes"]))
    maps = [json.loads(p.read_text()) for p in sorted((ROOT / "data/maps").glob("*_hns/map.json"))]
    tables = json.loads((ROOT / "data/spec/encounters_standard.json").read_text())["tables"]
    floors = map_floors(tables, maps)
    ceilings = map_floors([dict(t, min_level=t["max_level"]) for t in tables], maps)
    if set(t["map"] for t in tables) - set(floors):
        raise ValueError("Standard encounter map missing from trainer floors")
    lines = ["// Generated by tools/sync_tactica_trainer_levels.py; do not edit.",
             "static const bool8 sTacticaOrdinaryTrainers[] =", "{"]
    lines += [f"    [{trainer}] = TRUE," for trainer in ids]
    lines += ["};", "", "static const struct TacticaTrainerZoneFloor sTacticaTrainerZoneFloors[] =", "{"]
    lines += [f"    {{{name}, {level}, {ceilings[name]}}}," for name, level in sorted(floors.items())]
    return "\n".join(lines + ["};", ""])


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit("Trainer levels stale: run tools/sync_tactica_trainer_levels.py")
    else:
        OUTPUT.write_text(expected)
    print("Tactica ordinary trainer floors: " + ("checked" if args.check else "generated"))


if __name__ == "__main__":
    main()
